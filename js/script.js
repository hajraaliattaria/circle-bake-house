function observe() {
    const ob = new IntersectionObserver(
        (entries) => {
            entries.forEach((e) => {
                if (e.isIntersecting) {
                    e.target.classList.add("visible");
                }
            });
        },
        {
            threshold: 0.1
        }
    );

    document
        .querySelectorAll(".reveal:not(.observed)")
        .forEach((el) => {
            el.classList.add("observed");

            ob.observe(el);
        });
}


let lastSpark = 0;


function sparkleCursor(e) {
    const now = Date.now();

    if (now - lastSpark < 32) {
        return;
    }

    lastSpark = now;

    const dot =
        document.createElement("span");

    dot.className = "sparkle-dot";

    dot.style.left =
        e.clientX + "px";

    dot.style.top =
        e.clientY + "px";

    dot.style.setProperty(
        "--sx",
        (Math.random() * 34 - 17) + "px"
    );

    dot.style.setProperty(
        "--sy",
        (Math.random() * 34 - 17) + "px"
    );

    dot.style.width =
        dot.style.height =
            (Math.random() * 7 + 6) + "px";

    document.body.appendChild(dot);

    setTimeout(
        () => dot.remove(),
        760
    );
}


window.addEventListener(
    "mousemove",
    sparkleCursor,
    {
        passive: true
    }
);


