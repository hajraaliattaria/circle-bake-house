function renderTable(t) {
    return `
        <table>
            ${t
                .map(
                    (r, i) => `
                        <tr>
                            ${r
                                .map(
                                    (c) =>
                                        i
                                            ? `<td>${c}</td>`
                                            : `<th>${c}</th>`
                                )
                                .join("")}
                        </tr>
                    `
                )
                .join("")}
        </table>
    `;
}


function renderItem(i) {
    return `
        <div class="item">
            <div>
                <strong>${i[0]}</strong>
                ${i[1] ? `<small>${i[1]}</small>` : ""}
            </div>

            <span class="price">
                ${i[2]}
            </span>
        </div>
    `;
}


function renderMenu() {
    menuGrid.innerHTML = sections
        .map(
            (s) => `
                <article
                    class="menu-block reveal ${s.wide ? "wide" : ""}"
                    data-cat="${s.cat}"
                >
                    <div
                        class="menu-image"
                        style="background-image:url('${s.img}')"
                    >
                        <span>${s.title}</span>
                    </div>

                    <div class="menu-content">
                        <h3>${s.title}</h3>

                        ${(s.tables || [])
                            .map(renderTable)
                            .join("")}

                        ${
                            s.items
                                ? `
                                    <div class="menu-list">
                                        ${s.items
                                            .map(renderItem)
                                            .join("")}
                                    </div>
                                `
                                : ""
                        }
                    </div>
                </article>
            `
        )
        .join("");

    observe();
}


